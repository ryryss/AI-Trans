// 翻译目标语言：code -> 提示词里用的语言名
const AI_TRANS_TARGETS = {
  'zh-CN': 'Simplified Chinese',
  'zh-TW': 'Traditional Chinese',
  en: 'English',
  ja: 'Japanese',
  ko: 'Korean',
  de: 'German',
  fr: 'French',
  es: 'Spanish',
  ru: 'Russian',
  pt: 'Portuguese',
  it: 'Italian',
  ar: 'Arabic',
  hi: 'Hindi',
  th: 'Thai',
  vi: 'Vietnamese',
  nl: 'Dutch',
  pl: 'Polish',
  tr: 'Turkish',
  id: 'Indonesian'
};

// 把任意语言代码归一到我们支持的界面语言，找不到就回退英文
function aiTransLang(code) {
  const l = String(code || '').toLowerCase();
  if (AI_TRANS_I18N[l]) return l;
  if (l.startsWith('zh')) return l.includes('tw') || l.includes('hk') || l.includes('hant') ? 'zh-TW' : 'zh-CN';
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('ko')) return 'ko';
  if (l.startsWith('de')) return 'de';
  if (l.startsWith('fr')) return 'fr';
  if (l.startsWith('es')) return 'es';
  if (l.startsWith('ru')) return 'ru';
  if (l.startsWith('pt')) return 'pt-BR';
  return 'en';
}

// 浏览器默认语言（后台 worker 没有 navigator，用 chrome.i18n）
function aiTransDetect() {
  let l = 'en';
  try {
    if (typeof navigator !== 'undefined' && navigator.language) l = navigator.language;
    else if (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) l = chrome.i18n.getUILanguage();
  } catch (e) {}
  return aiTransLang(l);
}

// 根据界面语言推导默认的翻译目标语言
function aiTransDefaultTarget(lang) {
  const l = aiTransLang(lang);
  const map = { 'zh-CN': 'zh-CN', 'zh-TW': 'zh-TW', ja: 'ja', ko: 'ko', de: 'de', fr: 'fr', es: 'es', ru: 'ru', 'pt-BR': 'pt', en: 'en' };
  return map[l] || 'en';
}

// 取翻译字符串；{name} 占位符替换
function aiTransT(lang, key, vars) {
  const dict = AI_TRANS_I18N[aiTransLang(lang)] || AI_TRANS_I18N.en;
  let s = dict[key] != null ? dict[key] : (AI_TRANS_I18N.en[key] != null ? AI_TRANS_I18N.en[key] : key);
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  }
  return s;
}

// 把后台返回的错误码渲染成本地化文案（显示方用自己的界面语言调用）
function aiTransErrText(lang, code, detail) {
  const staticMap = {
    NO_KEY: 'errNoKey',
    NO_MODEL: 'errNoModel',
    EMPTY: 'errEmpty',
    BADJSON: 'errBadJSON',
    TIMEOUT: 'errTimeout',
    NETWORK: 'errNetwork',
    OLLAMA: 'errOllama',
    UNKNOWN: 'errUnknown'
  };
  let key = staticMap[code];
  let vars = null;
  if (!key && code && code.indexOf('HTTP_') === 0) {
    const st = parseInt(code.slice(5), 10);
    const hm = { 400: 'err400', 401: 'err401', 402: 'err402', 403: 'err403', 404: 'err404', 429: 'err429' };
    key = hm[st] || (st >= 500 ? 'err5xx' : 'errHTTP');
    if (key === 'err5xx' || key === 'errHTTP') vars = { s: st };
  }
  if (!key) key = 'errUnknown';
  let text = vars ? aiTransT(lang, key, vars) : aiTransT(lang, key);
  if (code === 'UNKNOWN' && detail) text = aiTransT(lang, 'errUnknown', { e: detail });
  else if (detail && detail.trim()) text += ' · ' + detail.trim();
  return text;
}
